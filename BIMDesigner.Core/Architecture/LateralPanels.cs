            {
                var (a, b) = (axis[i], axis[i + 1]);
                if ((value - a) * (value - b) <= 0) return (i, Math.Abs(b - a) < 1e-12 ? 0 : (value - a) / (b - a));
            }

            return (axis.Length - 2, 1);
        }

        var (row, down) = Place(Mus, mu);
        var (column, across) = Place(Ratios, ratio);
        double At(int r, int c) => table[r, c];
        var top = At(row, column) + across * (At(row, column + 1) - At(row, column));
        var bottom = At(row + 1, column) + across * (At(row + 1, column + 1) - At(row + 1, column));
        return top + down * (bottom - top);
    }

    /// <summary>
    /// The case for a panel's edges: of those whose every edge is held no more than the panel's own, the one giving the least coefficient - each edge taken as no stiffer than it is. None
    /// where no case fits: a panel with its top and a side free, or both sides free, which spans up its height alone.
    /// </summary>
    public static char? CaseFor(PanelEdge top, PanelEdge bottom, PanelEdge left, PanelEdge right, double mu, double ratio)
    {
        var (more, less) = left >= right ? (left, right) : (right, left);
        var fits = Cases.Where(each => each.Top <= top && each.Bottom <= bottom && each.More <= more && each.Less <= less && (each.Top == PanelEdge.Free) == (top == PanelEdge.Free)
                                       && (each.Less == PanelEdge.Free) == (less == PanelEdge.Free)).ToList();
        return fits.Count == 0 ? null : fits.MinBy(each => Coefficient(each.Case, mu, ratio)).Case;
    }

    /// <summary>
    /// A panel's α2, h and l in mm: the case's, or where it spans up its height alone, as α2 = M1 / (μ W l²) of a span simply supported, h²/8, or of a cantilever, h²/2, standing on its
    /// foot with its top free; past h/l of 2, where it spans along its length, no less than that span's own, l²/8 between two edges simply supported, l²/16 between two continuous.
    /// </summary>
    public static (double Alpha, string Said) Alpha(PanelEdge top, PanelEdge bottom, PanelEdge left, PanelEdge right, double mu, double height, double length)
    {
        mu = Math.Clamp(mu, 0.05, 1.0);
        var ratio = height / length;
        var letter = CaseFor(top, bottom, left, right, mu, ratio);
        if (letter is null)
        {
            var span = top == PanelEdge.Free ? 0.5 : 0.125;
            return (span * height * height / (mu * length * length), top == PanelEdge.Free ? "standing on its foot, its top free: h²/2" : "spanning up its height: h²/8");
        }

        var alpha = Coefficient(letter.Value, mu, ratio);
        if (ratio > 2 && left != PanelEdge.Free && right != PanelEdge.Free)
        {
            var along = left == PanelEdge.Continuous && right == PanelEdge.Continuous ? 1.0 / 16 : left == PanelEdge.Continuous || right == PanelEdge.Continuous ? 1 / 11.66 : 0.125;
            if (along > alpha) return (along, $"case {letter}, h/l {ratio:0.00} spanning along its length");
        }

        return (alpha, $"case {letter}, h/l {ratio:0.00}, μ {mu:0.00}");
    }
